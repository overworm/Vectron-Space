#!/usr/bin/env python3
"""gen_screens.py - the title picture: 256 x 144 (aspect kept, whole picture), 256 colours, 8bpp tiles for BG mode 3.
res/scr_0a.bin + scr_0b.bin (two halves, a ROM section is at most 32 KB), res/scr_pal.h"""
import os
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "art_src", "screens", "title.png")
OUT = os.path.join(HERE, "..", "res")


def to_tiles8(idx):
    h, w = idx.shape
    out = bytearray()
    for ty in range(h // 8):
        for tx in range(w // 8):
            t = idx[ty * 8:ty * 8 + 8, tx * 8:tx * 8 + 8]
            for pair in range(4):                       # planes (0,1) (2,3) (4,5) (6,7)
                for y in range(8):
                    a = b = 0
                    for x in range(8):
                        v = int(t[y, x])
                        a |= ((v >> (2 * pair)) & 1) << (7 - x)
                        b |= ((v >> (2 * pair + 1)) & 1) << (7 - x)
                    out += bytes((a, b))
    return bytes(out)

def convert(path, name):
    """picture -> res/<name>a.bin, <name>b.bin (+ returns the 256-colour palette); path None -> empty placeholders"""
    if path is None:
        open(os.path.join(OUT, name + "a.bin"), "wb").write(bytes(16))
        open(os.path.join(OUT, name + "b.bin"), "wb").write(bytes(16))
        return [(0, 0, 0)] * 256
    im = Image.open(path).convert("RGB")
    h = round(im.height * 256 / im.width)
    h = min(h, 144)
    im = im.resize((256, h), Image.LANCZOS)
    canvas = Image.new("RGB", (256, 144), (0, 0, 0))
    canvas.paste(im, (0, (144 - h) // 2))
    q = canvas.quantize(colors=256, method=Image.MEDIANCUT, kmeans=2, dither=Image.FLOYDSTEINBERG)
    pal = np.array(q.getpalette()[:768]).reshape(256, 3)
    pal = np.vstack([pal, np.zeros((256 - len(pal), 3), int)]) if len(pal) < 256 else pal
    idx = np.asarray(q).astype(np.uint8)
    order = sorted(range(256), key=lambda i: int(pal[i].sum()))
    remap = np.zeros(256, np.uint8)
    for new, old in enumerate(order):
        remap[old] = new
    idx = remap[idx]
    pal = pal[order]
    pal15 = [(int(r) >> 3, int(g) >> 3, int(b) >> 3) for r, g, b in pal]
    pal15[0] = (0, 0, 0)
    data = to_tiles8(idx)
    half = len(data) // 2
    open(os.path.join(OUT, name + "a.bin"), "wb").write(data[:half])
    open(os.path.join(OUT, name + "b.bin"), "wb").write(data[half:])
    prev = Image.fromarray(np.array([[pal15[i] for i in row] for row in idx], dtype=np.uint8) * 8, "RGB")
    prev.save(os.path.join(OUT, "sheets", name + ".png"))
    return pal15


def pal_c(arr, p):
    return "static const u16 %s[256] = {\n%s\n};\n" % (arr, ",".join("0x%04X" % ((b << 10) | (g << 5) | r) for r, g, b in p))


brief = None
mj = os.environ.get("STAGE_JSON") or os.path.join(HERE, "..", "maps", "stage1.json")
if os.path.exists(mj):
    import json
    b = json.load(open(mj)).get("briefing")
    if b and os.path.exists(os.path.join(HERE, "..", "maps", b)):
        brief = os.path.join(HERE, "..", "maps", b)
p0 = convert(SRC, "scr_0")
p1 = convert(brief, "scr_1")
with open(os.path.join(OUT, "scr_pal.h"), "w") as f:
    f.write("/* generated by tools/gen_screens.py */\n" + pal_c("scr_pal", p0) + pal_c("brief_pal", p1) + "#define HAS_BRIEF %d\n" % (1 if brief else 0))
print("screens ok, briefing:", bool(brief))
