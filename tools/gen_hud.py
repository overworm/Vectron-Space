def tile(rows):
    """rows: 8 strings of 8 chars: '.' = background (3), '1', '2'"""
    b = bytearray(32)
    for y, r in enumerate(rows):
        p0 = p1 = 0
        for x, ch in enumerate(r):
            v = 3 if ch == "." else int(ch)
            p0 |= (v & 1) << (7 - x)
            p1 |= (v >> 1) << (7 - x)
        b[2 * y], b[2 * y + 1] = p0, p1
    return bytes(b)


tiles = []
for ch in ORDER:
    g = F[ch].split()
    rows = []
    for y in range(8):
        if y < 7:
            rows.append("." + "".join("1" if c == "1" else "." for c in g[y]) + "..")
        else:
            rows.append("........")
    tiles.append(tile(rows))
tiles.append(tile(["........"] * 8))                 # 40 space / solid
