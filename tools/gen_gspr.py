#!/usr/bin/env python3
"""gen_gspr.py - enemy frames for the Super FX scaler (the close-up half of the hybrid renderer).
For every enemy type, the 20 frames of the biggest OBJ size (64x64, level 0) are decoded from the
SNES tiles, remapped into the 16-colour BG1 palette (the Super FX can only plot that one) and packed:
  2048 bytes a frame; byte [P*64 + row] = pixel(col 2P, row) | pixel(col 2P+1, row) << 4 ; 0 = transparent
Outputs: res/gspr_eT_a.bin / _b.bin (frames 0-9 / 10-19) and res/gspr.h (colour maps)."""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__)); R = os.path.join(HERE, "..", "res")

def c15(v): return ((v & 31), ((v >> 5) & 31), ((v >> 10) & 31))
txt = open(os.path.join(R, "palette.h")).read()
bg0 = [int(x, 16) for x in re.search(r"bg_pal\[9\]\[16\] = \{\s*\{([^}]*)\}", txt).group(1).replace("0x", "").split(",")]
sd = open(os.path.join(R, "spr_defs.h")).read()
body = re.search(r"enemy_pal_data\[7\]\[16\] = \{(.*?)\};", sd, re.S).group(1)
pals = [[int(x, 16) for x in row.replace("0x", "").split(",")] for row in re.findall(r"\{([^}]*)\}", body)]
assert len(pals) == 7 and all(len(p) == 16 for p in pals)

def nearest(col):
    r, g, b = c15(col); best, bd = 1, 1 << 30
    for i in range(1, 16):
        rr, gg, bb = c15(bg0[i])
        d = 3 * (r - rr) ** 2 + 4 * (g - gg) ** 2 + 2 * (b - bb) ** 2 + 6 * (((r*3+g*6+b)//10) - ((rr*3+gg*6+bb)//10)) ** 2
        if d < bd: bd, best = d, i
    return best

def decode(d, f):
    px = [[0] * 64 for _ in range(64)]
    for tr in range(8):
        for tc in range(8):
            o = f * 2048 + (tr * 8 + tc) * 32
            for y in range(8):
                b0, b1, b2, b3 = d[o + 2*y], d[o + 2*y + 1], d[o + 16 + 2*y], d[o + 17 + 2*y]
                for x in range(8):
                    s = 7 - x
                    px[tr*8 + y][tc*8 + x] = ((b0 >> s) & 1) | (((b1 >> s) & 1) << 1) | (((b2 >> s) & 1) << 2) | (((b3 >> s) & 1) << 3)
    return px

maps = []
for t in range(7):
    m = [0] + [nearest(pals[t][i]) for i in range(1, 16)]
    maps.append(m)
    n0 = open(os.path.join(R, f"spr_e{t}_n0.bin"), "rb").read()
    nb = open(os.path.join(R, f"spr_e{t}_nb.bin"), "rb").read()
    out = bytearray()
    for f in range(20):
        px = decode(n0, f) if f < 15 else decode(nb, f - 15)
        fr = bytearray(2048)
        for P in range(32):
            for r in range(64):
                fr[P*64 + r] = m[px[r][2*P]] | (m[px[r][2*P + 1]] << 4)
        out += fr
    open(os.path.join(R, f"gspr_e{t}_a.bin"), "wb").write(out[:10 * 2048])
    open(os.path.join(R, f"gspr_e{t}_b.bin"), "wb").write(out[10 * 2048:])
with open(os.path.join(R, "gspr.h"), "w") as f:
    f.write("/* generated by tools/gen_gspr.py: enemy colour -> BG1 palette entry (what the Super FX plots) */\n")
    f.write("static const u8 gspr_map[7][16] = {\n" + ",\n".join("{" + ",".join(str(v) for v in m) + "}" for m in maps) + "\n};\n")
print("ok", maps[0])
