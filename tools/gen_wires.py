#!/usr/bin/env python3
"""gen_wires.py - art of the wires minigame -> res/spr_wire.bin (one 64x64 canvas = one weapon slot, 2048 B) and res/wire_pal.h
canvas quarters (32x32 sprites): TL round switch, knob up (1) | TR round switch, knob left (0) | BL thick wire band | BR: tile (4,4) = white current dot"""
import os, math
import numpy as np
from PIL import Image, ImageDraw
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "res")


def to_tiles(idx):
    out = bytearray()
    for ty in range(8):
        for tx in range(8):
            b = bytearray(32)
            for y in range(8):
                p = [0, 0, 0, 0]
                for x in range(8):
                    c = int(idx[ty * 8 + y, tx * 8 + x]) & 15
                    for k in range(4):
                        p[k] |= ((c >> k) & 1) << (7 - x)
                b[y * 2], b[y * 2 + 1], b[16 + y * 2], b[16 + y * 2 + 1] = p
            out += b
    return bytes(out)


def px(im, x, y, c):
    if 0 <= x < 32 and 0 <= y < 32:
        im[y][x] = c


DIG = {"1": ["010", "110", "010", "010", "111"], "0": ["111", "101", "101", "101", "111"]}


def text(im, x0, y0, ch, c):
    for j, row in enumerate(DIG[ch]):
        for i, v in enumerate(row):
            if v == "1":
                px(im, x0 + i, y0 + j, c)


def dial(up):
    im = [[0] * 32 for _ in range(32)]
    cx = cy = 15.5
    for y in range(32):
        for x in range(32):
            d = math.hypot(x - cx, y - cy)
            if d <= 14.5: im[y][x] = 1                      # black outline
            if d <= 13.5: im[y][x] = 3                      # ring
            if d <= 11.5: im[y][x] = 2                      # face
            if d <= 13.5 and d > 11.5 and (x - cx) + (y - cy) < -4: im[y][x] = 4     # light top-left edge of the ring
    if up:
        for y in range(4, 17):
            for x in range(14, 18): im[y][x] = 5 if x in (15, 16) else 1
        for x in range(14, 18): im[3][x] = 1
        text(im, 22, 5, "1", 5); text(im, 4, 22, "0", 3)
    else:
        for x in range(4, 17):
            for y in range(14, 18): im[y][x] = 5 if y in (15, 16) else 1
        for y in range(14, 18): im[y][3] = 1
        text(im, 22, 5, "1", 3); text(im, 4, 22, "0", 5)
    for y in range(13, 19):                                  # hub
        for x in range(13, 19):
            if math.hypot(x - 15.5, y - 15.5) <= 3.2: im[y][x] = 5 if math.hypot(x - 15.5, y - 15.5) <= 2.2 else 1
    return np.array(im, np.uint8)


def band():
    im = np.zeros((32, 32), np.uint8)
    for y in range(9, 23):
        c = 3 if y in (9, 22) else 1
        if y in (11, 12): c = 2
        im[y, :] = c
    return im


def dot():
    im = np.zeros((32, 32), np.uint8)
    for y in range(8):
        for x in range(8):
            d = math.hypot(x - 3.5, y - 3.5)
            if d <= 3.9: im[128 // 128 * 0 + 4 * 0 + y, x] = 5 if d <= 2.6 else 4
    return im


cv = np.zeros((64, 64), np.uint8)
cv[0:32, 0:32] = dial(True)
cv[0:32, 32:64] = dial(False)
cv[32:64, 0:32] = band()
cv[32:64, 32:64] = dot()
data = to_tiles(cv)
assert len(data) == 2048
open(os.path.join(OUT, "spr_wire.bin"), "wb").write(data)


def c15(r, g, b): return (b << 10) | (g << 5) | r


pal_dial = [0, c15(1, 1, 2), c15(5, 6, 7), c15(11, 11, 12), c15(20, 20, 22), c15(31, 31, 31)] + [c15(31, 31, 31)] * 10
pal_sel = [0, c15(3, 2, 0), c15(9, 7, 0), c15(30, 25, 2), c15(31, 29, 12), c15(31, 31, 31)] + [c15(31, 31, 31)] * 10
pal_mx = [0, c15(0, 6, 0), c15(6, 26, 6), c15(30, 25, 2), c15(31, 29, 12), c15(31, 31, 31)] + [c15(0, 6, 0)] * 4 + [c15(30, 25, 2)] + [c15(6, 26, 6)] * 5   # digits: idx 1/2; the chosen switch: idx 1..5 (green face, yellow ring)
wires = [((27, 3, 3), (31, 18, 16), (11, 0, 0)), ((3, 9, 27), (14, 21, 31), (0, 2, 11)),
         ((29, 25, 2), (31, 30, 15), (11, 9, 0)), ((5, 5, 6), (15, 15, 17), (0, 0, 0))]
pal_w = [[0, c15(*b), c15(*h), c15(*o)] + [c15(*b)] * 12 for b, h, o in wires]
with open(os.path.join(OUT, "wire_pal.h"), "w") as f:
    f.write("/* generated by tools/gen_wires.py: OBJ palettes of the wires minigame (1 switch, 3 matrix digits and yellow brackets, 4..7 red/blue/yellow/black wires) */\n")
    f.write("static const u16 wire_pal_sw[16] = {%s};\n" % ",".join("0x%04X" % c for c in pal_dial))
    f.write("static const u16 wire_pal_sel[16] = {%s};\n" % ",".join("0x%04X" % c for c in pal_sel))
    f.write("static const u16 wire_pal_mx[16] = {%s};\n" % ",".join("0x%04X" % c for c in pal_mx))
    f.write("static const u16 wire_pal_w[4][16] = {%s};\n" % ",".join("{" + ",".join("0x%04X" % c for c in p) + "}" for p in pal_w))
# preview
pv = Image.new("RGB", (64, 64), (0, 40, 0))
for y in range(64):
    for x in range(64):
        v = cv[y, x]
        if v:
            pv.putpixel((x, y), [(0, 0, 0), (5, 6, 8), (45, 50, 56), (95, 95, 100), (160, 160, 175), (255, 255, 255)][min(v, 5)])
pv.resize((256, 256), Image.NEAREST).save(os.path.join(HERE, "art_src", "wire_preview.png"))
print("wires ok")
