#!/usr/bin/env python3
"""gen_level.py - builds res/level.h: the 32x32 map (wall texture ids), the
sector triggers, the teleport pads of every wave and the boss position."""
import os, sys
from collections import deque
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "res")
N = 32
HULL, HAZ, CON, DOOR, PIPE, GRAT, WIN, BOSS = 1, 2, 3, 4, 5, 6, 7, 8

# (x0,y0,x1,y1, theme)   inclusive, tiles
AREAS = {
    "A":  (2, 2, 8, 8, "start"),
    "c1": (9, 4, 16, 5, "corr"),
    "B":  (17, 2, 26, 10, "labb"),
    "c2": (21, 11, 22, 16, "corr"),
    "C":  (14, 17, 28, 24, "labc"),
    "c3": (8, 20, 13, 21, "corr"),
    "D":  (2, 16, 7, 25, "labd"),
    "c4": (3, 26, 4, 29, "corr"),
    "c5": (5, 28, 17, 29, "corr2"),
    "E":  (18, 26, 30, 30, "boss"),
}
PILLARS = [(20, 5), (23, 5), (20, 8), (23, 8), (17, 20), (17, 22), (25, 20), (25, 22),
           (21, 20), (21, 21), (4, 19), (5, 22), (6, 18), (21, 28), (24, 27), (24, 30 - 1)]

zone = [[None] * N for _ in range(N)]
free = [[False] * N for _ in range(N)]
for name, (x0, y0, x1, y1, th) in AREAS.items():
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            free[y][x] = True
            zone[y][x] = th
for (x, y) in PILLARS:
    free[y][x] = False

def theme_wall(th, x, y, horizontal):
    k = (x * 7 + y * 13) % 11
    if th == "start":
        return CON if k in (0, 1, 5) else (WIN if k == 3 else HULL)
    if th == "corr":
        return PIPE if k % 2 == 0 else (HAZ if k in (1, 7) else HULL)
    if th == "corr2":
        return HAZ if k in (0, 4, 8) else (PIPE if k % 2 else HULL)
    if th == "labb":
        return WIN if k in (0, 3, 6) else (CON if k == 8 else HULL)
    if th == "labc":
        return GRAT if k in (0, 2, 4, 6) else (PIPE if k == 9 else HULL)
    if th == "labd":
        return CON if k in (0, 2, 5, 7) else (DOOR if k == 9 else HULL)
    if th == "boss":
        return BOSS
    return HULL

mp = [[HULL] * N for _ in range(N)]
for y in range(N):
    for x in range(N):
        if free[y][x]:
            mp[y][x] = 0
for y in range(N):
    for x in range(N):
        if free[y][x]:
            continue
        ths = []
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            xx, yy = x + dx, y + dy
            if 0 <= xx < N and 0 <= yy < N and free[yy][xx]:
                ths.append(zone[yy][xx])
        if ths:
            mp[y][x] = theme_wall(ths[0], x, y, False)
# pillars: lighter console blocks
for (x, y) in PILLARS:
    mp[y][x] = CON if (x + y) % 2 else PIPE
# the door frame at the boss room entrance
for y in (26, 27, 30):
    mp[y][17] = DOOR if y != 30 else mp[y][17]
mp[27][17] = DOOR
for x in range(N):
    mp[0][x] = mp[0][x] or HULL
    mp[N - 1][x] = mp[N - 1][x] or HULL
    mp[x][0] = mp[x][0] or HULL
    mp[x][N - 1] = mp[x][N - 1] or HULL

START = (3.5, 3.5)
BOSSPOS = (27.5, 28.5)
# triggers: x0,y0,x1,y1, wave
TRIGGERS = [
    (18, 3, 25, 9, 0),
    (15, 18, 27, 23, 1),
    (3, 17, 6, 24, 2),
    (9, 28, 12, 29, 3),
    (19, 27, 21, 29, 4),   # boss room entrance: wakes the boss + guards
]
WAVES = [
    [(19.5, 3.5), (25.5, 3.5), (25.5, 9.5)],
    [(15.5, 18.5), (27.5, 18.5), (15.5, 23.5), (27.5, 23.5)],
    [(2.5, 17.5), (2.5, 24.5), (6.5, 24.5)],
    [(5.5, 28.5), (6.5, 29.0)],
    [(19.5, 26.5), (19.5, 30.0)],
]

# connectivity check
seen = set([(int(START[0]), int(START[1]))])
q = deque(seen)
while q:
    x, y = q.popleft()
    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
        nx, ny = x + dx, y + dy
        if 0 <= nx < N and 0 <= ny < N and mp[ny][nx] == 0 and (nx, ny) not in seen:
            seen.add((nx, ny))
            q.append((nx, ny))
assert (int(BOSSPOS[0]), int(BOSSPOS[1])) in seen, "boss unreachable"
for w in WAVES:
    for (x, y) in w:
        assert mp[int(y)][int(x)] == 0, ("pad in wall", x, y)
total_free = sum(1 for y in range(N) for x in range(N) if mp[y][x] == 0)
assert len(seen) == total_free, ("unreachable floor", total_free - len(seen))

for y in range(N):
    print("".join(".#hc dpgwb"[0] if False else (".12345678"[mp[y][x]] if mp[y][x] else " ") for x in range(N)))

def fx(v):
    return int(round(v * 256))

with open(os.path.join(OUT, "level.h"), "w") as f:
    f.write("/* generated by tools/gen_level.py */\n#ifndef LEVEL_H\n#define LEVEL_H\n")
    f.write("static const u8 level_map[1024] = {\n")
    for y in range(N):
        f.write(",".join(str(mp[y][x]) for x in range(N)) + ",\n")
    f.write("};\n")
    f.write("#define START_X %d\n#define START_Y %d\n" % (fx(START[0]), fx(START[1])))
    f.write("#define BOSS_X %d\n#define BOSS_Y %d\n" % (fx(BOSSPOS[0]), fx(BOSSPOS[1])))
    f.write("#define NUM_TRIGGERS %d\n" % len(TRIGGERS))
    f.write("static const u8 trig_rect[%d][5] = {\n" % len(TRIGGERS))
    for t in TRIGGERS:
        f.write("{%d,%d,%d,%d,%d},\n" % t)
    f.write("};\n")
    f.write("#define NUM_WAVES %d\n" % len(WAVES))
    f.write("static const u8 wave_count[%d] = {%s};\n" % (len(WAVES), ",".join(str(len(w)) for w in WAVES)))
    f.write("static const s16 wave_pad[%d][4][2] = {\n" % len(WAVES))
    for w in WAVES:
        pads = list(w) + [w[0]] * (4 - len(w))
        f.write("{" + ",".join("{%d,%d}" % (fx(x), fx(y)) for x, y in pads) + "},\n")
    f.write("};\n#endif\n")
print("level ok, free tiles", total_free)
